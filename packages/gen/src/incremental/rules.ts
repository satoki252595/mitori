/**
 * Early cutoff R1–R8 (gen spec §11.3) as a pure function of the doc's generated sections, the claim states and the
 * S9 baselines vs the current index. One suggestion per unit — a module page (`s6/<slug>`), the flows (`s3` with its
 * sub-sections), the opening (`s0`–`s2`, suggested under `s0`), `s7`, `s9`…`s13` — where a regeneration rule beats
 * the doc.sync patch of the same unit; R7 may add the labels of new modules (`s5`). Stale ratio = stale claims /
 * claims of the unit's AI blocks (blocks excluded by the caller do not count).
 */
import type { BlockId, ModuleId, SectionId, Xxh3 } from "@mitori/core";
import type { GenPromptId, IncrementalRule, IncrementalSuggestion } from "../contract.ts";
import type { Fingerprints, S9State } from "./state.ts";

/** Stale ratio above which a unit is regenerated instead of patched (R2, R8). */
export const STALE_RATIO_REGEN = 0.2;

/** Claim state of one AI block. */
export interface BlockClaims {
  /** Block. */
  id: BlockId;
  /** Claims. */
  total: number;
  /** Stale claims. */
  stale: number;
}

/** A unit the rules evaluate. */
export interface Unit {
  /** Suggestion section (`s6/<slug>`, `s3`, `s0`, `s7`, `s9`…`s13`). */
  section: SectionId;
  /** Module of a page unit. */
  module?: { id: ModuleId; leaf: boolean; children: ModuleId[]; iface: Xxh3 };
  /** AI blocks of the unit with their claim counts. */
  blocks: BlockClaims[];
}

/** A suggestion before its estimate and id. */
export type SuggestionSpec = Pick<IncrementalSuggestion, "section" | "reason" | "rule" | "kind" | "prompt" | "blocks">;

/** Regeneration prompt per non-module unit. */
const SECTION_PROMPT: Partial<Record<string, GenPromptId>> = {
  s0: "gen.overview",
  s3: "gen.flows",
  s7: "gen.datamodel",
  s9: "gen.quality",
  s10: "gen.decisions",
  s11: "gen.risks",
  s12: "gen.glossary",
  s13: "gen.questions",
};

/** Units of R8 (§9–§13). */
const R8_UNITS = new Set(["s9", "s10", "s11", "s12", "s13"]);

/** Unit of a doc section (null: not generated by a prompt). */
export function unitOf(section: SectionId, isModule: boolean): SectionId | null {
  if (isModule) return section;
  const top = section.split("/")[0] as string;
  if (top === "s0" || top === "s1" || top === "s2") return "s0";
  if (top === "s3") return "s3";
  return top in SECTION_PROMPT ? (top as SectionId) : null;
}

/** Everything the rules read. */
export interface RuleInput {
  /** Units with generated content. */
  units: readonly Unit[];
  /** Baselines. */
  base: S9State;
  /** Current fingerprints. */
  now: Fingerprints;
  /** Modules that only have their provisional name (labels of R7). */
  unlabeled: readonly ModuleId[];
}

function sync(u: Unit, rule: IncrementalRule): SuggestionSpec | null {
  const blocks = u.blocks.filter((b) => b.stale > 0).map((b) => b.id);
  return blocks.length > 0 ? { section: u.section, reason: "stale_ratio", rule, kind: "sync", prompt: "doc.sync", blocks } : null;
}

const regen = (section: SectionId, rule: IncrementalRule, reason: SuggestionSpec["reason"], prompt: GenPromptId): SuggestionSpec => ({
  section,
  reason,
  rule,
  kind: "regen",
  prompt,
  blocks: [],
});

/** Stale ratio of a unit. */
export function staleRatio(u: Pick<Unit, "blocks">): number {
  const total = u.blocks.reduce((n, b) => n + b.total, 0);
  return total === 0 ? 0 : u.blocks.reduce((n, b) => n + b.stale, 0) / total;
}

/** Evaluate R1–R8. Suggestions come out in unit order. */
export function evaluate(input: RuleInput): SuggestionSpec[] {
  const { base, now } = input;
  const ifaceChanged = (id: ModuleId, iface: Xxh3) => base.iface[id] !== undefined && base.iface[id] !== iface;
  const r1 = new Set(input.units.filter((u) => u.module?.leaf && ifaceChanged(u.module.id, u.module.iface)).map((u) => u.module?.id as ModuleId));
  const changed = (b: Xxh3 | undefined, n: Xxh3) => b !== undefined && b !== n;
  const out: SuggestionSpec[] = [];
  const push = (s: SuggestionSpec | null) => {
    if (s) out.push(s);
  };
  for (const u of input.units) {
    const m = u.module;
    if (m) {
      const prompt: GenPromptId = m.leaf ? "gen.module" : "gen.parent";
      if (m.leaf && r1.has(m.id)) push(regen(u.section, "R1", "iface_changed", prompt));
      // R4 only when a child changed its interface AND the parent's own digest changed: no upward propagation otherwise
      else if (!m.leaf && ifaceChanged(m.id, m.iface) && m.children.some((c) => r1.has(c))) push(regen(u.section, "R4", "iface_changed", prompt));
      else if (staleRatio(u) > STALE_RATIO_REGEN) push(regen(u.section, "R2", "stale_ratio", prompt));
      else push(sync(u, "R3"));
      continue;
    }
    const prompt = SECTION_PROMPT[u.section];
    if (!prompt) continue;
    if (u.section === "s3" && changed(base.flows, now.flows)) push(regen("s3", "R5", "facts_changed", prompt));
    else if (u.section === "s7" && changed(base.schema, now.schema)) push(regen("s7", "R6", "facts_changed", prompt));
    else if (u.section === "s0" && changed(base.structure, now.structure)) {
      push(regen("s0", "R7", "iface_changed", prompt));
      if (input.unlabeled.length > 0) push({ section: "s5", reason: "new_symbols", rule: "R7", kind: "regen", prompt: "gen.labels", blocks: [] });
    } else if (R8_UNITS.has(u.section) && staleRatio(u) > STALE_RATIO_REGEN) push(regen(u.section, "R8", "stale_ratio", prompt));
    else push(sync(u, R8_UNITS.has(u.section) ? "R8" : "R3"));
  }
  return out;
}
