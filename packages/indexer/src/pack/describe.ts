/**
 * Provisional one-line module descriptions (0 token, before gen writes its own), in this order:
 *
 * 1. the package / module doc comment of the module's directories (its dominant directory, then its largest child
 *    directories): Go `// Package x …` in any file of the package, Python module docstring of `__init__.py`, Rust
 *    `//!` / `/*! … *\/` of `lib.rs` / `mod.rs` / `main.rs`, a leading JS/TS `/** @module … *\/` of `index.*`;
 * 2. the `description` of the manifest of that directory (`package.json`, `Cargo.toml`, `pyproject.toml`), never the
 *    repository root's;
 * 3. a structural line: `18 files · Session, ReviewFile, Load` (file count and the main exported names).
 *
 * One sentence, ≤ 120 characters, in the source's language; gen writes the Japanese summary later.
 */
import type { RepoPath } from "@mitori/core";
import type { ModuleDetail, SkeletonTier } from "../contract.ts";
import { baseOf, dirOf, type StageFile } from "../resolve/files.ts";
import { visibleControls } from "./visible.ts";

export interface DescribeIo {
  /** File fragment text of a tier (secret-scanned), or null. */
  docSkeleton(path: RepoPath, tier: SkeletonTier): string | null;
  /** Texts of the manifests the resolver read (package.json, Cargo.toml, pyproject.toml …). */
  manifest(path: RepoPath): string | null;
  /** PageRank of a file. */
  rank(path: RepoPath): number;
  /** LOC of a directory's whole subtree (graph files). */
  subtreeLoc(dir: string): number;
}

const MAX = 120;
/** Files that carry a module doc, by language convention (Go: any file of the package, see `isPackageDoc`). */
const DOC_FILES = /^(doc\.go|__init__\.py|lib\.rs|mod\.rs|main\.rs|index\.(ts|tsx|js|jsx|mjs|mts))$/;
const LICENSE = /\b(copyright|license[ds]?|spdx|all rights reserved|generated by|code generated|do not edit)\b/i;
/** Tool directives that open many files but describe nothing. */
const DIRECTIVE = /^(eslint|@ts-|prettier|biome-|go:|\+build|nolint|noqa|pylint|pragma|@flow|@format|@jsx|istanbul|type:\s*ignore|!\/|-\*-)/i;
/** JSDoc tags that introduce a file's description (the tag itself is dropped). */
const FILE_TAG = /^@(module|file|fileoverview|overview|packageDocumentation)\b\s*/i;
const MANIFESTS = ["package.json", "Cargo.toml", "pyproject.toml"];
/** Exported names a structural description lists: types first, then functions. */
const TYPE_KINDS = new Set(["class", "struct", "interface", "trait", "enum", "type"]);
const FUNC_KINDS = new Set(["function", "macro"]);
/** Share of a package's subtree a module must hold to borrow the package's manifest description. */
const OWN_SHARE = 0.5;
/** Child directories (besides the dominant one) whose docs are tried. */
const CHILD_DIRS = 3;

/** First sentence of a paragraph, ≤ 120 chars. */
function sentence(text: string): string {
  const t = text.replace(/\s+/g, " ").trim();
  const m = /^(.+?[.。!?！？])(\s|$)/.exec(t);
  const s = (m ? (m[1] as string) : t).trim();
  return s.length > MAX ? `${s.slice(0, MAX - 1)}…` : s;
}

/**
 * The first paragraph of the leading comment of a numbered fragment (`=== header` then `N|line` rows): line comments
 * (`//`, `//!`, `#`), block comments (`/** … *\/`, `/*! … *\/`) and Python docstrings; directives and license headers
 * are skipped.
 */
export function leadingDoc(fragment: string, path: RepoPath = ""): string | null {
  const lang = /\.go$/.test(path) ? "go" : /\.rs$/.test(path) ? "rust" : /\.pyi?$/.test(path) ? "python" : /\.[cm]?[jt]sx?$/.test(path) ? "js" : "";
  const doc: string[] = [];
  let mode: "none" | "block" | "py" = "none";
  let pyQuote = "";
  /** The comment came with a file tag (`@module`, `@file`) or a crate doc marker (`//!`, `/*!`). */
  let tagged = false;
  let lastDocLine = 0;
  let nextLine = 0;
  for (const raw of fragment.split("\n").slice(1)) {
    const m = /^(\d+)\|(.*)$/.exec(raw);
    if (!m) break;
    const n = Number(m[1]);
    let l = (m[2] as string).trim();
    if (mode === "py") {
      const end = l.indexOf(pyQuote);
      const body = end >= 0 ? l.slice(0, end) : l;
      if (body.trim() === "" && doc.length > 0) break;
      if (body.trim() !== "") doc.push(body.trim());
      if (end >= 0) break;
      continue;
    }
    if (mode === "block") {
      const end = l.indexOf("*/");
      const body = (end >= 0 ? l.slice(0, end) : l).replace(/^\*\s?/, "").trim();
      lastDocLine = n;
      if (end >= 0) mode = "none";
      if (body === "" && doc.length > 0) {
        if (mode === "block") break;
        continue;
      }
      if (body !== "" && !DIRECTIVE.test(body)) {
        if (/^@/.test(body) && !FILE_TAG.test(body)) break;
        if (FILE_TAG.test(body)) tagged = true;
        const t = body.replace(FILE_TAG, "");
        if (t !== "") doc.push(t);
      }
      continue;
    }
    if (doc.length > 0 || tagged) {
      // first code line after the comment: a JS/TS comment directly above a declaration documents the declaration
      nextLine = n;
    }
    const py = lang === "python" || lang === "" ? /^(r|u|b)?("""|''')/.exec(l) : null;
    if (py) {
      pyQuote = py[2] as string;
      l = l.slice(py[0].length);
      const end = l.indexOf(pyQuote);
      if (end >= 0) {
        if (l.slice(0, end).trim() !== "") doc.push(l.slice(0, end).trim());
        break;
      }
      if (l.trim() !== "") doc.push(l.trim());
      mode = "py";
      continue;
    }
    const block = /^\/\*([*!]?)\s?(.*)$/.exec(l);
    if (block) {
      if (doc.length > 0) break;
      if (block[1] === "!") tagged = true;
      const rest = block[2] as string;
      const end = rest.indexOf("*/");
      if (FILE_TAG.test(rest)) tagged = true;
      const body = (end >= 0 ? rest.slice(0, end) : rest).replace(FILE_TAG, "").trim();
      if (body !== "" && !DIRECTIVE.test(body)) doc.push(body);
      lastDocLine = n;
      if (end < 0) mode = "block";
      continue;
    }
    const line = /^(\/\/[/!]?|#!?)\s?(.*)$/.exec(l);
    if (!line) break;
    const marker = line[1] as string;
    // Rust `///` and JS `///` document the next item, Go and Python files have their own conventions
    if (marker === "///" || (lang === "rust" && marker !== "//!") || (lang === "python" && marker.startsWith("#"))) break;
    if (marker === "//!") tagged = true;
    const body = (line[2] as string).trim();
    if (DIRECTIVE.test(body)) continue;
    if (body === "") {
      if (doc.length > 0) break;
      continue;
    }
    doc.push(body);
    lastDocLine = n;
  }
  const text = doc.join(" ").trim();
  if (text === "" || LICENSE.test(text)) return null;
  // JS / TS: an untagged comment glued to the next line documents that declaration, not the file
  if (lang === "js" && !tagged && nextLine !== 0 && nextLine === lastDocLine + 1) return null;
  if (lang === "rust" && !tagged) return null;
  return text;
}

/** `description = "…"` / `"description": "…"` of a manifest. */
function manifestDescription(path: RepoPath, text: string): string | null {
  if (path.endsWith(".json")) {
    try {
      const d = (JSON.parse(text) as { description?: unknown }).description;
      return typeof d === "string" && d.trim() !== "" ? d : null;
    } catch {
      return null;
    }
  }
  // TOML: multi-line ("""…""" / '''…''') or one-line ("…" / '…') strings
  const m = /^\s*description\s*=\s*(?:"""([\s\S]*?)"""|'''([\s\S]*?)'''|"((?:[^"\\]|\\.)*)"|'([^']*)')/m.exec(text);
  const v = m ? (m[1] ?? m[2] ?? m[3] ?? m[4] ?? "").replace(/\\"/g, '"').trim() : "";
  return v !== "" ? v : null;
}

/** Directories whose docs describe the module: its dominant directory, then its largest child directories. */
function docDirs(m: ModuleDetail, paths: readonly RepoPath[], files: ReadonlyMap<RepoPath, StageFile>): string[] {
  const dir = m.dominantDir === "." ? "" : m.dominantDir;
  const by = new Map<string, number>();
  for (const p of paths) {
    const d = dirOf(p);
    if (d !== dir && !(dir === "" || d.startsWith(`${dir}/`))) continue;
    by.set(d, (by.get(d) ?? 0) + Math.max(1, files.get(p)?.loc ?? 0));
  }
  const kids = [...by]
    .filter(([d]) => d !== dir)
    .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
    .slice(0, CHILD_DIRS)
    .map(([d]) => d);
  return [dir, ...kids];
}

/** A Go package comment names its package (`// Package session …`); other languages use their doc files. */
const isPackageDoc = (path: RepoPath, doc: string) => (path.endsWith(".go") ? /^Package\s/.test(doc) : true);

/** One-line description of a module (leaf or parent) from its member files. */
export function moduleSummary(m: ModuleDetail, paths: readonly RepoPath[], files: ReadonlyMap<RepoPath, StageFile>, io: DescribeIo): string {
  const byRank = (xs: readonly RepoPath[]) => [...xs].sort((a, b) => io.rank(b) - io.rank(a) || (a < b ? -1 : 1));
  const loc = paths.reduce((a, p) => a + Math.max(1, files.get(p)?.loc ?? 0), 0);
  for (const dir of docDirs(m, paths, files)) {
    const inDir = paths.filter((p) => dirOf(p) === dir);
    // Go: any file of the package may hold its comment; elsewhere the conventional doc file
    const cands = inDir.filter((p) => p.endsWith(".go") || DOC_FILES.test(baseOf(p)));
    for (const p of byRank(cands)) {
      const frag = io.docSkeleton(p, "doc");
      const d = frag === null ? null : leadingDoc(frag, p);
      if (d !== null && isPackageDoc(p, d)) return visibleControls(sentence(d));
    }
    // the manifest of the directory or of its nearest ancestor below the repository root (a crate's `src/`) — an
    // ancestor's only when the module is most of that package (else every module of the package says the same)
    for (let d = dir; d !== ""; d = dirOf(d)) {
      if (loc < OWN_SHARE * io.subtreeLoc(d)) break;
      for (const name of MANIFESTS) {
        const path = `${d}/${name}`;
        const text = io.manifest(path);
        const desc = text === null ? null : manifestDescription(path, text);
        if (desc !== null) return visibleControls(sentence(desc));
      }
    }
  }
  const names: string[] = [];
  const ranked = byRank(paths);
  for (const kinds of [TYPE_KINDS, FUNC_KINDS])
    for (const p of ranked)
      for (const x of files.get(p)?.symbols ?? []) {
        if (names.length >= 3) break;
        if (x.exported && x.parent === undefined && kinds.has(x.kind) && !names.includes(x.name)) names.push(x.name);
      }
  const head = paths.length === 1 ? "1 file" : `${paths.length} files`;
  return visibleControls(names.length > 0 ? `${head} · ${names.join(", ")}` : head);
}
