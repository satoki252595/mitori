// Export-name index of every package's public surface → docs/design/briefs/INDEX.md (SC-12).
// Usage: bun scripts/contract-index.ts [--check]   (--check: exit 1 when INDEX.md is stale)
import { writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import ts from "typescript";
import { ROOT, read } from "./lib/repo.ts";

const OUT = "docs/design/briefs/INDEX.md";
const PKGS: [string, string][] = [
  ["@mitori/core", "packages/core/src/index.ts"],
  ["@mitori/platform", "packages/platform/src/index.ts"],
  ["@mitori/indexer", "packages/indexer/src/index.ts"],
  ["@mitori/doc", "packages/doc/src/index.ts"],
  ["@mitori/anchor", "packages/anchor/src/index.ts"],
  ["@mitori/agent", "packages/agent/src/index.ts"],
  ["@mitori/gen", "packages/gen/src/index.ts"],
  ["@mitori/loop", "packages/loop/src/index.ts"],
  ["@mitori/server", "packages/server/src/index.ts"],
  ["@mitori/client", "packages/client/src/index.ts"],
  ["@mitori/testkit", "packages/testkit/src/index.ts"],
  ["@mitori/web", "apps/web/src/index.ts"],
];

function kindOf(d: ts.Declaration): string {
  if (ts.isInterfaceDeclaration(d) || ts.isTypeAliasDeclaration(d)) return "types";
  if (ts.isFunctionDeclaration(d)) return "functions";
  if (ts.isClassDeclaration(d)) return "classes";
  if (ts.isVariableDeclaration(d)) return "consts";
  return "other";
}

export function buildIndex(): string {
  const program = ts.createProgram(
    PKGS.map(([, f]) => join(ROOT, f)),
    {
      target: ts.ScriptTarget.ES2023,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      allowImportingTsExtensions: true,
      noEmit: true,
      types: [],
      skipLibCheck: true,
      resolveJsonModule: true,
    },
  );
  const checker = program.getTypeChecker();
  const lines = [
    "# Contract export index",
    "",
    "> Generated by `bun scripts/contract-index.ts` from each package's `src/index.ts` — do not edit. `bun run check` fails when it is stale:",
    "> a change here is a change of a public surface (contract-change CR batch, `packages/core/CR-LEDGER.md`). Re-exports name their source package.",
    "",
  ];
  const summary: string[] = [];
  const body: string[] = [];
  for (const [pkg, entry] of PKGS) {
    const sf = program.getSourceFile(join(ROOT, entry));
    const mod = sf && checker.getSymbolAtLocation(sf);
    if (!mod) throw new Error(`cannot load ${entry}`);
    const pkgDir = entry.replace(/\/src\/index\.ts$/, "");
    const byFile = new Map<string, Map<string, string[]>>();
    const exports = checker.getExportsOfModule(mod);
    for (const ex of exports) {
      const target = ex.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(ex) : ex;
      const decl = target.declarations?.[0];
      if (!decl) continue;
      const file = relative(ROOT, decl.getSourceFile().fileName).replace(/^node_modules\/@mitori\/[^/]+\//, "");
      const inPkg = file.startsWith(`${pkgDir}/`);
      const key = inPkg ? file.slice(pkgDir.length + 1) : `re-exported from ${/^(packages|apps)\/([^/]+)\//.exec(file)?.[2] ?? file}`;
      const kind = kindOf(decl);
      const kinds = byFile.get(key) ?? new Map<string, string[]>();
      byFile.set(key, kinds);
      const list = kinds.get(kind) ?? [];
      kinds.set(kind, list);
      list.push(ex.name === target.name ? ex.name : `${ex.name} (= ${target.name})`);
    }
    summary.push(`${pkg.replace("@mitori/", "")} ${exports.length}`);
    body.push(`## ${pkg} — ${exports.length} exports`, "");
    for (const file of [...byFile.keys()].sort()) {
      const kinds = byFile.get(file) as Map<string, string[]>;
      const parts = [...kinds.keys()].sort().map((k) => `${k}: ${(kinds.get(k) as string[]).sort().join(", ")}`);
      body.push(`- **${file}** — ${parts.join("; ")}`);
    }
    body.push("");
  }
  return `${[...lines, `Totals: ${summary.join(" · ")}`, "", ...body].join("\n").trimEnd()}\n`;
}

if (import.meta.main) {
  const next = buildIndex();
  if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = read(OUT);
    } catch {}
    if (cur !== next) {
      console.error(`contract-index: ${OUT} is stale — run \`bun run contract:index\` and review the public-surface diff`);
      process.exit(1);
    }
    console.log("contract-index: ok");
  } else {
    writeFileSync(join(ROOT, OUT), next);
    console.log(`contract-index: wrote ${OUT}`);
  }
}
